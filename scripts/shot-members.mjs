import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
/** 项目成员卡 + 管理弹窗实拍（D-30）。 */
const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'docs', 'screenshots');
mkdirSync(OUT, { recursive: true });
const BASE = process.env.SHOT_BASE ?? 'http://localhost:5173';
const PASSWORD = process.env.SEED_ADMIN_PASSWORD ?? '';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1880, height: 1080 }, locale: 'zh-CN', ignoreHTTPSErrors: process.env.SHOT_INSECURE === '1' });
const page = await ctx.newPage();
await page.goto(`${BASE}/login`, { waitUntil: 'networkidle' });
await page.getByPlaceholder(/用户名|账号/).first().fill('admin');
await page.getByPlaceholder(/密码/).first().fill(PASSWORD);
await page.getByRole('button', { name: /登\s*录/ }).click();
await page.waitForTimeout(2500);
await page.goto(`${BASE}/projects/3`, { waitUntil: 'networkidle' });
await page.waitForTimeout(2200);
const chips = await page.locator('.wb-member-chip').count();
console.log(`${chips > 0 ? '✓' : '✗'} 成员卡显示 ${chips} 人`);
await page.screenshot({ path: join(OUT, '47-项目成员.png') });
await page.getByRole('button', { name: '管理成员' }).click();
await page.waitForTimeout(1200);
const modal = await page.locator('.ant-modal-content').first().isVisible().catch(() => false);
console.log(`${modal ? '✓' : '✗'} 成员弹窗打开`);
await page.screenshot({ path: join(OUT, '48-成员管理弹窗.png') });
await browser.close();
